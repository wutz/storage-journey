def speak(s):
    s = s.replace('mmvdisk', 'm m v disk').replace('mmapi', 'm m A P I')
    for a, b in SPEAK:
        s = re.sub(rf'(?<![A-Za-z]){re.escape(a)}(?![A-Za-z])', b, s)
    return s


